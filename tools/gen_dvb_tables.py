#!/usr/bin/env python3
"""Generate src/dvb_tables.cpp from DVB parity-bit address tables.

The input headers are the 0BSD-licensed tables of https://github.com/xdsopl/LDPC
(dvb_s2_tables.hh, dvb_s2x_tables.hh, dvb_t2_tables.hh), which were transcribed
from ETSI EN 302 307-1 (DVB-S2), EN 302 307-2 (DVB-S2X) and EN 302 755 (DVB-T2).

Usage: gen_dvb_tables.py <dir-with-headers> <output.cpp>
"""
import re
import sys

# (header, struct name) -> (standard, frame, rate name)
CODES = {
    "S2": ("dvb_s2_tables.hh", "DVB_S2_TABLE_", "DvbStandard::S2", [
        ("B1", "Normal", "1/4"), ("B2", "Normal", "1/3"), ("B3", "Normal", "2/5"),
        ("B4", "Normal", "1/2"), ("B5", "Normal", "3/5"), ("B6", "Normal", "2/3"),
        ("B7", "Normal", "3/4"), ("B8", "Normal", "4/5"), ("B9", "Normal", "5/6"),
        ("B10", "Normal", "8/9"), ("B11", "Normal", "9/10"),
        ("C1", "Short", "1/4"), ("C2", "Short", "1/3"), ("C3", "Short", "2/5"),
        ("C4", "Short", "1/2"), ("C5", "Short", "3/5"), ("C6", "Short", "2/3"),
        ("C7", "Short", "3/4"), ("C8", "Short", "4/5"), ("C9", "Short", "5/6"),
        ("C10", "Short", "8/9")]),
    "S2X": ("dvb_s2x_tables.hh", "DVB_S2X_TABLE_", "DvbStandard::S2X", [
        ("B1", "Normal", "2/9"), ("B2", "Normal", "13/45"), ("B3", "Normal", "9/20"),
        ("B4", "Normal", "11/20"), ("B5", "Normal", "26/45"), ("B6", "Normal", "28/45"),
        ("B7", "Normal", "23/36"), ("B8", "Normal", "25/36"), ("B9", "Normal", "13/18"),
        ("B10", "Normal", "7/9"), ("B11", "Normal", "90/180"), ("B12", "Normal", "96/180"),
        ("B13", "Normal", "100/180"), ("B14", "Normal", "104/180"), ("B15", "Normal", "116/180"),
        ("B16", "Normal", "124/180"), ("B17", "Normal", "128/180"), ("B18", "Normal", "132/180"),
        ("B19", "Normal", "135/180"), ("B20", "Normal", "140/180"), ("B21", "Normal", "154/180"),
        ("B22", "Normal", "18/30"), ("B23", "Normal", "20/30"), ("B24", "Normal", "22/30"),
        ("C1", "Short", "11/45"), ("C2", "Short", "4/15"), ("C3", "Short", "14/45"),
        ("C4", "Short", "7/15"), ("C5", "Short", "8/15"), ("C6", "Short", "26/45"),
        ("C7", "Short", "32/45"),
        ("C8", "Medium", "1/5"), ("C9", "Medium", "11/45"), ("C10", "Medium", "1/3")]),
    "T2": ("dvb_t2_tables.hh", "DVB_T2_TABLE_", "DvbStandard::T2", [
        ("A1", "Normal", "1/2"), ("A2", "Normal", "3/5"), ("A3", "Normal", "2/3"),
        ("A4", "Normal", "3/4"), ("A5", "Normal", "4/5"), ("A6", "Normal", "5/6"),
        ("B1", "Short", "1/4"), ("B2", "Short", "1/2"), ("B3", "Short", "3/5"),
        ("B4", "Short", "2/3"), ("B5", "Short", "3/4"), ("B6", "Short", "4/5"),
        ("B7", "Short", "5/6"), ("B8", "Short", "1/3"), ("B9", "Short", "2/5")]),
}

FRAME_N = {"Normal": 64800, "Medium": 32400, "Short": 16200}


def parse_structs(text):
    out = {}
    for m in re.finditer(r"struct (\w+)\s*\{(.*?)\n\};", text, re.S):
        body = m.group(2)

        def scalar(name):
            return int(re.search(r"\b" + name + r"\s*=\s*(\d+)", body).group(1))

        def array(name):
            arr = re.search(r"\b" + name + r"\[\]\s*=\s*\{(.*?)\}", body, re.S).group(1)
            return [int(x) for x in re.findall(r"\d+", arr)]

        deg = array("DEG")
        length = array("LEN")
        # Arrays are zero-terminated.
        groups = [(d, l) for d, l in zip(deg, length) if d and l]
        out[m.group(1)] = dict(N=scalar("N"), K=scalar("K"), M=scalar("M"),
                               links_total=scalar("LINKS_TOTAL"),
                               cn_min=scalar("LINKS_MIN_CN"), cn_max=scalar("LINKS_MAX_CN"),
                               groups=groups, pos=array("POS"))
    return out


def check_degrees(t):
    """Builds the check-node degree histogram (incl. the staircase) for validation."""
    n, k, m = t["N"], t["K"], t["M"]
    p = n - k
    q = p // m
    deg = [0] * p
    pos = iter(t["pos"])
    for d, count in t["groups"]:
        for _ in range(count):
            base = [next(pos) for _ in range(d)]
            for j in range(m):
                for b in base:
                    deg[(b + j * q) % p] += 1
    for i in range(p):
        deg[i] += 1 if i == 0 else 2
    return min(deg), max(deg), sum(deg)


def main():
    src_dir, out_path = sys.argv[1], sys.argv[2]
    lines = [
        "// Generated by tools/gen_dvb_tables.py -- do not edit.",
        "//",
        "// DVB-S2 / DVB-S2X / DVB-T2 LDPC parity-bit address tables, transcribed from",
        "// ETSI EN 302 307-1, EN 302 307-2 and EN 302 755 by Ahmet Inan and Ron Economos",
        "// (https://github.com/xdsopl/LDPC, 0BSD license).",
        "",
        '#include "dvb_tables.hpp"',
        "",
        "namespace ldpc {",
        "namespace detail {",
        "namespace {",
        "",
    ]
    entries = []
    for key, (header, prefix, std_enum, codes) in CODES.items():
        structs = parse_structs(open(f"{src_dir}/{header}").read())
        for tag, frame, rate in codes:
            t = structs[prefix + tag]
            assert t["N"] == FRAME_N[frame], (key, tag)
            assert t["M"] == 360
            assert sum(d * c for d, c in t["groups"]) == len(t["pos"]), (key, tag)
            assert sum(c for _, c in t["groups"]) * 360 == t["K"], (key, tag)
            assert max(t["pos"]) < t["N"] - t["K"], (key, tag)
            cmin, cmax, total = check_degrees(t)
            assert (cmin, cmax) == (t["cn_min"], t["cn_max"]), (key, tag, cmin, cmax)
            assert total == t["links_total"], (key, tag, total)
            ident = f"k{key}_{frame}_{rate.replace('/', '_')}"
            degs = ", ".join(str(d) for d, _ in t["groups"])
            cnts = ", ".join(str(c) for _, c in t["groups"])
            lines.append(f"const std::uint16_t {ident}_deg[] = {{{degs}}};")
            lines.append(f"const std::uint16_t {ident}_cnt[] = {{{cnts}}};")
            lines.append(f"const std::uint16_t {ident}_pos[] = {{")
            row = []
            for v in t["pos"]:
                row.append(str(v))
                if len(row) == 16:
                    lines.append("    " + ", ".join(row) + ",")
                    row = []
            if row:
                lines.append("    " + ", ".join(row) + ",")
            lines.append("};")
            lines.append("")
            entries.append(
                f"    {{{std_enum}, DvbFrameSize::{frame}, \"{rate}\", {t['N']}, {t['K']}, "
                f"{len(t['groups'])}, {ident}_deg, {ident}_cnt, {ident}_pos, "
                f"{cmin}, {cmax}, {total}}},")
    lines += ["}  // namespace", "", "const DvbTable kDvbTables[] = {"] + entries + [
        "};",
        "",
        "const std::size_t kDvbTableCount = sizeof(kDvbTables) / sizeof(kDvbTables[0]);",
        "",
        "}  // namespace detail",
        "}  // namespace ldpc",
        "",
    ]
    open(out_path, "w").write("\n".join(lines))
    print(f"wrote {len(entries)} tables to {out_path}")


if __name__ == "__main__":
    main()
